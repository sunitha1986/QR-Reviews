/**
 * Retrieve saved theme ID, optionally scoped per business identifier (clientId, phone, or qrId)
 */
export function getSavedThemeId(businessId) {
  try {
    if (businessId) {
      const cleanId = String(businessId).trim();
      const perBusinessTheme = localStorage.getItem(`qr_theme_${cleanId}`);
      if (perBusinessTheme && COLOR_THEMES.some(t => t.id === perBusinessTheme)) {
        return perBusinessTheme;
      }
    }
    const globalTheme = localStorage.getItem('qr_sidebar_theme');
    if (globalTheme && COLOR_THEMES.some(t => t.id === globalTheme)) {
      return globalTheme;
    }
    return 'royal-violet';
  } catch {
    return 'royal-violet';
  }
}

/**
 * Save theme ID scoped per business and globally
 */
export function saveThemeForBusiness(businessId, themeId) {
  if (!themeId) return;
  try {
    if (businessId) {
      const cleanId = String(businessId).trim();
      localStorage.setItem(`qr_theme_${cleanId}`, themeId);
    }
    localStorage.setItem('qr_sidebar_theme', themeId);
  } catch (e) {
    // ignore
  }
}

export function applyColorTheme(themeId, businessId) {
  const targetId = themeId || getSavedThemeId(businessId);
  const theme = COLOR_THEMES.find(t => t.id === targetId) || COLOR_THEMES[0];
  const root = document.documentElement;

  // Primary colors & glows
  root.style.setProperty('--primary', theme.primary);
  root.style.setProperty('--primary-hover', theme.primaryHover);
  root.style.setProperty('--primary-glow', theme.primaryGlow);
  root.style.setProperty('--secondary', theme.accent);
  root.style.setProperty('--accent', theme.accent);

  // Button gradient & themed button shadows
  root.style.setProperty('--theme-btn-gradient', theme.buttonGradient);
  root.style.setProperty('--theme-btn-gradient-hover', theme.buttonGradientHover);
  root.style.setProperty('--theme-btn-shadow', theme.buttonShadow);
  root.style.setProperty('--theme-btn-shadow-hover', theme.buttonShadowHover);

  // Scrollbar colors & gradients
  root.style.setProperty('--theme-scrollbar-thumb', theme.primary);
  root.style.setProperty('--theme-scrollbar-thumb-hover', theme.accent);
  root.style.setProperty('--theme-scrollbar-gradient', theme.scrollbarGradient);
  root.style.setProperty('--theme-scrollbar-track', theme.scrollbarTrack);

  // Background radial ambient shades
  root.style.setProperty('--theme-bg-glow-1', theme.bgGlow1);
  root.style.setProperty('--theme-bg-glow-2', theme.bgGlow2);
  root.style.setProperty('--theme-bg-glow-3', theme.bgGlow3);
  root.style.setProperty('--theme-bg-glow-light-1', theme.bgGlowLight1);
  root.style.setProperty('--theme-bg-glow-light-2', theme.bgGlowLight2);

  // Cards borders, tinted backgrounds, and colored glow shadows
  root.style.setProperty('--theme-card-border', theme.cardBorder);
  root.style.setProperty('--theme-card-border-hover', theme.cardBorderHover);
  root.style.setProperty('--theme-card-shadow', theme.cardShadow);
  root.style.setProperty('--theme-card-shadow-hover', theme.cardShadowHover);
  root.style.setProperty('--theme-card-bg-tint', theme.cardBgTint);
  root.style.setProperty('--theme-sidebar-gradient', theme.gradient);

  root.setAttribute('data-color-theme', theme.id);

  saveThemeForBusiness(businessId, theme.id);

  return theme;
}
